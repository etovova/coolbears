import assert from 'node:assert/strict';
import {keys,seal,unseal,checkRequest,checkSource} from './pinata-private-recovery.mjs';
const k=keys('TEST_ONLY_NOT_A_REAL_CREDENTIAL_'+'a'.repeat(64));
const value={secretUrl:'https://dl.dropboxusercontent.com/test-only',test:true},sealed=seal(value,k.publicDer);
assert.deepEqual(unseal(sealed,k),value);
assert.equal(JSON.stringify(sealed).includes(value.secretUrl),false);
assert.throws(()=>unseal({...sealed,ciphertext:Buffer.alloc(50).toString('base64')},k));
assert.throws(()=>unseal(sealed,keys('TEST_ONLY_NOT_A_REAL_CREDENTIAL_'+'b'.repeat(64))));
assert.throws(()=>keys(''));
for(const url of ['http://dl.dropboxusercontent.com/a','https://attacker.test/a','https://dropbox.com.attacker.test/a','https://user:pass@dropbox.com/a','https://127.0.0.1/a'])assert.throws(()=>checkSource(url));
assert.doesNotThrow(()=>checkSource(value.secretUrl));
const now=Date.now(),r={action:'backup-private-recovery-v3',sha256:'00c983a1af436b60008505ad3cd706615bd5a3e01cf1186a7127cbdde69f3252',size:153849791,url:value.secretUrl,expiresAt:now+600000};
assert.doesNotThrow(()=>checkRequest(r,now));
assert.throws(()=>checkRequest({...r,expiresAt:now-1},now));
assert.throws(()=>checkRequest({...r,expiresAt:now+900001},now));
assert.throws(()=>checkRequest({...r,action:'public-upload'},now));
assert.throws(()=>checkRequest({...r,sha256:'0'.repeat(64)},now));

// Offline draft only. No active package, client configuration or release flags change.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import * as core from '@ton/core';
import {CID} from 'multiformats/cid';
import {sha256} from 'multiformats/hashes/sha2';
import {verifyPackage,PACKAGE_SHA256} from '../launch/package-tools.mjs';

const root=process.env.COOLBEARS_DESCRIPTION_RELEASE;
assert.ok(root&&path.isAbsolute(root));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const raw=fs.readFileSync('launch/candidate.json'),p=JSON.parse(raw);
assert.equal(sha(raw),PACKAGE_SHA256);
const state=JSON.parse(fs.readFileSync('release/launch-state.json'));
assert.equal(state.phase,'hold');
for(const k of ['mainnetVerified','creatorNftVerified','publicMintApproved','automaticRevealArmed'])assert.equal(state[k],false);
const proof=JSON.parse(fs.readFileSync(path.join(root,'description-proof.json')));
const mb=fs.readFileSync(path.join(root,'manifest.PRIVATE.json')),m=JSON.parse(mb);
assert.equal(sha(mb),proof.manifestSha256);
assert.equal(proof.sourceCarSha256,p.releaseCarSha256);
assert.equal(proof.sourceManifestSha256,p.releaseManifestSha256);
assert.equal(proof.sourceCarExactlyVerified,true);
assert.equal(proof.unchangedPngFiles,10000);
assert.equal(proof.unchangedMetadataFiles,10000);
const colBytes=fs.readFileSync('metadata/collection.json');
const col=JSON.parse(colBytes),finalCol=JSON.parse(fs.readFileSync(path.join(root,'collection.json')));
assert.equal(finalCol.description,col.description);
assert.ok(!/reserved|зарезервир|预留/i.test(col.description));
const ccid=CID.createV1(0x55,await sha256.digest(colBytes)).toString();
const publicDir='release/description-correction';fs.mkdirSync(publicDir,{recursive:true});
const car=path.join(root,'prereveal-collection.car');
const packed=execFileSync('node_modules/.bin/ipfs-car',['pack','--no-wrap','metadata/collection.json','--output',car],{encoding:'utf8'}).trim();
assert.equal(packed,ccid);
const v=verifyPackage(core,p),d=v.data;
const content=core.beginCell().storeRef(core.beginCell().storeUint(1,8).storeStringTail('ipfs://'+ccid).endCell()).storeRef(core.beginCell().storeStringTail(p.preRevealMetadataRootIpfs).endCell()).endCell();
const final=core.beginCell().storeRef(core.beginCell().storeUint(1,8).storeStringTail(m.collectionMetadataIpfs).endCell()).storeRef(core.beginCell().storeStringTail(m.metadataRootIpfs).endCell()).endCell();
const commitment=final.hash().toString('hex');
const data=core.beginCell().storeAddress(d.owner).storeUint(0,64).storeRef(content).storeRef(d.item).storeRef(d.royalty).storeAddress(d.treasury).storeBit(true).storeBit(false).storeUint(BigInt('0x'+commitment),256).endCell();
const init={code:v.init.code,data},address=core.contractAddress(0,init);
const bounce=address.toString({bounceable:true,testOnly:false}),nonbounce=address.toString({bounceable:false,testOnly:false});
const boc=core.beginCell().store(core.storeStateInit(init)).endCell().toBoc().toString('base64');
const out={...p,status:'UNSIGNED_DESCRIPTION_CORRECTION_OFFLINE_ONLY',collectionAddressRaw:address.toRawString(),collectionAddressMainnetBounceable:bounce,collectionAddressMainnetNonBounceable:nonbounce,stateInitBocBase64:boc,collectionMetadataIpfs:'ipfs://'+ccid,metadataRevision:'approved-description-1',descriptionRevision:'approved-description-1',finalContentCommitment:commitment,releaseManifestSha256:proof.manifestSha256,releaseCarSha256:proof.carSha256,tonConnectDeployMessage:{...p.tonConnectDeployMessage,address:nonbounce,stateInit:boc},tonConnectCreatorClaimRequest:{...p.tonConnectCreatorClaimRequest,messages:[{...p.tonConnectCreatorClaimRequest.messages[0],address:bounce}]}};
const checked=verifyPackage(core,out);
for(const k of ['owner','treasury'])assert.ok(checked.data[k].equals(d[k]));
for(const k of ['item','royalty'])assert.ok(checked.data[k].equals(d[k]));
assert.ok(checked.init.code.equals(v.init.code));
assert.notEqual(commitment,p.finalContentCommitment);
const bytes=JSON.stringify(out,null,2)+'\n';
fs.mkdirSync(path.join(root,'unsigned-packages'),{recursive:true,mode:0o700});
fs.writeFileSync(path.join(root,'unsigned-packages/mainnet.candidate.json'),bytes);
fs.writeFileSync(path.join(publicDir,'unsigned-candidate.json'),bytes);
fs.writeFileSync(path.join(root,'unsigned-packages/reveal.PRIVATE.json'),JSON.stringify({schema:1,collectionAddressRaw:address.toRawString(),codeHash:p.collectionCodeHash,commitment,revealAt:p.revealAt,contentBoc:final.toBoc().toString('base64'),bundleCid:m.bundleCid,carSha256:proof.carSha256},null,2)+'\n');
const report={...proof,sourcePackageSha256:sha(raw),packageSha256:sha(bytes),collectionAddressMainnetNonBounceable:nonbounce,collectionAddressTestnetNonBounceable:address.toString({bounceable:false,testOnly:true}),collectionMetadataIpfs:'ipfs://'+ccid,collectionJsonSha256:sha(colBytes),finalContentCommitment:commitment,unchangedCode:true,unchangedHiddenNftMetadata:true,activated:false,publicMetadataPinned:false,privateStorageMigrationVerified:false,liveTestnetVerified:false};
fs.writeFileSync(path.join(publicDir,'preparation.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
